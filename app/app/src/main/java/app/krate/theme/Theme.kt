/**
 * Material 3 Expressive.
 *
 * [MaterialExpressiveTheme] rather than `MaterialTheme` is what makes this expressive rather than
 * merely Material You: it is the only entry point that carries a [MotionScheme], and the motion
 * scheme is what gives every component its spring-based, overshooting response instead of the
 * fixed-duration easing of baseline M3. Colour alone does not make a theme expressive.
 *
 * It is public only from material3 **1.5.0** onward — in 1.4.0, which the Compose BOM resolves,
 * this function and `expressive*ColorScheme` are `internal`. Hence the explicit version pin in
 * `libs.versions.toml`; do not drop it back to the BOM's version without checking that first.
 *
 * Dynamic colour is kept: on Android 12+ the palette comes from the user's wallpaper, which is the
 * Material You half of the promise. The hand-built schemes below are the fallback for Android 11
 * and earlier, seeded from KRATE's own brand colour.
 */
@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@Composable
fun KrateTheme(
  darkTheme: Boolean = isSystemInDarkTheme(),
  // Dynamic color is available on Android 12+
  dynamicColor: Boolean = true,
  content: @Composable () -> Unit,
) {
  val colorScheme =
    when {
      dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
        val context = LocalContext.current
        if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
      }
      darkTheme -> DarkColorScheme
      else -> LightColorScheme
    }

  MaterialExpressiveTheme(
    colorScheme = colorScheme,
    motionScheme = MotionScheme.expressive(),
    typography = Typography,
    content = content,
  )
}
